from scripts.corpus import tokenize_corpus as tc
from scripts.corpus.quality import reject_reason

GOOD = '"""Small arithmetic helpers."""\n\n\ndef add(a, b):\n    """Return the sum of a and b."""\n    return a + b\n\n\nprint(add(1, 2))\n'


def test_good_code_kept():
    assert reject_reason(GOOD, "code", "pkg/math.py") is None


def test_rules():
    assert reject_reason("print 'hi'\n" * 20, "code") == "syntax"
    assert reject_reason("x = 1\n", "code") == "too_short"
    assert reject_reason("# Generated by Django 3.2\n" + GOOD, "code") == "autogenerated"
    assert reject_reason(GOOD, "code", "app/migrations/0001_initial.py") == "migration"
    assert reject_reason("DATA = [" + "1, " * 600 + "]\n", "code") == "long_lines"
    assert reject_reason("X = [\n" + "    101, 202, 303,\n" * 50 + "]\n", "code") == "low_alpha"
    assert reject_reason(GOOD + "KEY = 'AKIAABCDEFGHIJKLMNOP'\n", "code") == "secret"


def test_prose_only_secret_checked():
    assert reject_reason("Not Python at all, just prose.", "prose_docs") is None
    assert reject_reason("token ghp_" + "a" * 36, "prose_docs") == "secret"


def test_tokenizer_pass_drops_and_counts():
    from tokenizers import Tokenizer

    tok = Tokenizer.from_file(str(tc.TOK_DIR / "tokenizer.json"))
    recs = [{"text": t, "meta": {"source_family": "code", "source_url": "o/r", "record_id": i}}
            for i, t in enumerate([GOOD, "print 'x'\n" * 20])]
    _, _, _, docs, dropped = tc.encode_records(tok, recs)
    assert sum(docs.values()) == 1 and dropped == {"syntax": 1}
