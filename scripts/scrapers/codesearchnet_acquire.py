def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def normalize_newlines(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n")


def normalize_code_for_hash(code: str) -> str:
    """Deterministic normalization used as the canonical dedup key.

    Mirrors the project-wide convention (``validate_content_hash``): line
    endings -> ``\\n``, trailing whitespace stripped per line.
    """
    code = normalize_newlines(code)
    return "\n".join(line.rstrip() for line in code.split("\n"))


def content_hash(code: str) -> str:
    return sha256_text(normalize_code_for_hash(code))


def utc_now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def make_run_id(seed: str) -> str:
    timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    return f"csn-{TRANSFORMATION_VERSION}-{timestamp}-{sha256_text(seed)[:8]}"


