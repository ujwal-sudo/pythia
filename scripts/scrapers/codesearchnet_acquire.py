def detect_license_identifier(license_text: str) -> Optional[str]:
    """Return a best-effort SPDX identifier from raw license text, or None."""
    if not license_text or not license_text.strip():
        return None
    text = license_text

    # Ordered: most specific / unambiguous first.
    if "GNU AFFERO GENERAL PUBLIC LICENSE" in text or "AGPL" in text.upper():
        return "AGPL-3.0"
    if "GNU LESSER GENERAL PUBLIC LICENSE" in text:
        if "Version 2.1" in text or "February 1999" in text:
            return "LGPL-2.1"
        return "LGPL-3.0"
    if "GNU GENERAL PUBLIC LICENSE" in text or "GPL" in text.upper():
        if "Version 3" in text or "29 June 2007" in text:
            return "GPL-3.0"
        if "Version 2" in text or "June 1991" in text:
            return "GPL-2.0"
        return "GPL-3.0"

    if "Mozilla Public License" in text or "MPL 2.0" in text or "MPL-2.0" in text:
        return "MPL-2.0"
    if "Eclipse Public License - v 2.0" in text:
        return "EPL-2.0"
    if "Eclipse Public License" in text:
        return "EPL-1.0"

    if "Apache License" in text and ("http://www.apache.org/licenses/LICENSE-2.0" in text or "Version 2.0" in text):
        return "Apache-2.0"

    if "Creative Commons Zero" in text or "CC0 1.0" in text:
        return "CC0-1.0"

    if "PYTHON SOFTWARE FOUNDATION LICENSE" in text or "Python Software Foundation License" in text:
        return "Python-2.0"

    if "This is free and unencumbered software released into the public domain" in text:
        return "Unlicense"

    if "DO WHAT THE FUCK YOU WANT TO PUBLIC LICENSE" in text:
        return "WTFPL"

    if "BLUE OAK MODEL LICENSE" in text:
        return "BlueOak-1.0.0"

    if "This software is provided 'as-is'" in text and "zlib" in text.lower():
        return "Zlib"

    if "Permission is hereby granted, free of charge, to any person obtaining a copy" in text:
        return "MIT"

    if "Redistribution and use in source and binary forms" in text:
        if "neither the name" in text.lower():
            return "BSD-3-Clause"
        return "BSD-2-Clause"

    if "Permission to use, copy, modify, and/or distribute" in text and "zero-clause" in text.lower():
        return "0BSD"

    return None


def classify_license(nwo: str, license_entries: List[Tuple[str, str]]) -> Dict[str, Any]:
    """Classify per-repository license evidence into a license_status."""
    if not nwo:
        return _license_decision(PROVENANCE_INSUFFICIENT, None, [], "missing repository identity")

    texts = [content for _, content in license_entries if content and content.strip()]
    if not texts:
        return _license_decision(
            LICENSE_REVIEW_REQUIRED, None, license_entries, "no license text recovered"
        )

    identifiers: List[str] = []
    for content in texts:
        detected = detect_license_identifier(content)
        if detected:
            identifiers.append(detected)

    if not identifiers:
        return _license_decision(
            LICENSE_REVIEW_REQUIRED, "UNKNOWN", license_entries, "license text not matched to a known identifier"
        )

    unique = sorted(set(identifiers))
    if len(unique) > 1:
        # Multiple distinct license identifiers in one repository.
        if all(ident in PERMISSIVE_LICENSES for ident in unique):
            status = LICENSE_APPROVED
        else:
            status = LICENSE_REVIEW_REQUIRED
        return _license_decision(status, ",".join(unique), license_entries, "multiple license identifiers detected")

    identifier = unique[0]
    if identifier in PERMISSIVE_LICENSES:
        status = LICENSE_APPROVED
    elif identifier in COPLEYFT_LICENSES:
        status = LICENSE_REVIEW_REQUIRED
    else:
        status = LICENSE_REVIEW_REQUIRED
    return _license_decision(status, identifier, license_entries, "single license identifier detected")


def _license_decision(
    status: str,
    identifier: Optional[str],
    entries: List[Tuple[str, str]],
    reason: str,
) -> Dict[str, Any]:
    return {
        "license_status": status,
        "license_identifier": identifier,
        "license_evidence_paths": [p for p, _ in entries],
        "license_evidence_text": "\n".join(c for _, c in entries)[:2000] if entries else None,
        "classification_reason": reason,
    }


