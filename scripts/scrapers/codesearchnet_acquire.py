def make_record_id(
    repo: str,
    path: str,
    func_name: str,
    sha: str,
    partition: str,
    content_digest: str,
) -> str:
    """Stable per-record id: source identity plus a content discriminator.

    Source identity alone is not unique in CodeSearchNet: the same
    ``repo/path/func_name/commit/partition`` tuple can map to multiple distinct
    code bodies (e.g. same-named nested functions or property getter/setter pairs
    on adjacent lines).  Folding in the normalized-content digest makes the id
    unique for every distinct body while identical bodies still share an id.
    """
    seed = "\x00".join([repo, path, func_name, sha, partition, content_digest])
    return "csn_" + sha256_text(seed)[:24]


def build_canonical_record(
    source_record: Dict[str, Any],
    license_info: Dict[str, Any],
    quality: Dict[str, Any],
    source_file: str,
    line_number: int,
    run_id: str,
    acquisition_date: str,
) -> Dict[str, Any]:
    repo = source_record.get("repo", "")
    path = source_record.get("path", "")
    func_name = source_record.get("func_name", "")
    sha = source_record.get("sha", "")
    partition = source_record.get("partition", "")
    code = source_record.get("code", "")
    docstring = source_record.get("docstring", "")

    code_h = content_hash(code)
    doc_h = sha256_text(normalize_newlines(docstring)) if docstring else None
    record_id = make_record_id(repo, path, func_name, sha, partition, code_h)

    return {
        "schema_version": SCHEMA_VERSION,
        "transformation_version": TRANSFORMATION_VERSION,
        "source": SOURCE,
        "source_family": SOURCE_FAMILY,
        "source_type": "raw",
        "source_dataset": SOURCE_DATASET,
        "source_version": ZENODO_DOI,
        "source_url": source_record.get("url", ""),
        "acquisition_date": acquisition_date,
        "run_id": run_id,
        "record_id": record_id,
        "original_record_id": f"{repo}::{path}::{func_name}::{sha}",
        "repository_name": repo,
        "file_path": path,
        "func_name": func_name,
        "language": source_record.get("language", ""),
        "commit_sha": sha,
        "split": partition,
        "code": code,
        "docstring": docstring,
        "documentation_type": "docstring",
        "original_string": source_record.get("original_string", ""),
        "content_hash": code_h,
        "normalized_hash": code_h,
        "docstring_hash": doc_h,
        "license": license_info.get("license_identifier"),
        "license_status": license_info.get("license_status"),
        "license_evidence_paths": license_info.get("license_evidence_paths", []),
        "license_classification_reason": license_info.get("classification_reason"),
        "attribution_notice_required": license_info.get("license_status") == LICENSE_APPROVED,
        "ast_parse_status": "valid" if quality["ast_valid"] else "invalid",
        "quality_status": quality["quality_status"],
        "rejection_reasons": quality["rejection_reasons"],
        "line_count": quality["line_count"],
        "char_count": quality["char_count"],
        "comment_ratio": quality["comment_ratio"],
        "provisional_token_count": max(1, quality["char_count"] // 4),
        "token_count_status": "PROVISIONAL",
        "dedup_status": "pending",
        "eligibility": "eligible" if quality["quality_status"] == "ACCEPTED" else "ineligible",
        "source_file": source_file,
        "source_line": line_number,
        "source_specific": {
            "code_tokens_len": len(source_record.get("code_tokens", [])),
            "docstring_tokens_len": len(source_record.get("docstring_tokens", [])),
        },
    }


# ---------------------------------------------------------------------------
# Duplicate audit (non-destructive)
# ---------------------------------------------------------------------------

def duplicate_audit(records: Sequence[Dict[str, Any]]) -> Dict[str, Any]:
    record_ids = [r["record_id"] for r in records]
    content_hashes = [r["content_hash"] for r in records]
    source_ids = [r["original_record_id"] for r in records]

    def dup_map(values: Iterable[Any]) -> Dict[str, int]:
        counts = Counter(values)
        return {str(k): c for k, c in sorted(counts.items()) if c > 1}

    return {
        "records_audited": len(records),
        "distinct_record_ids": len(set(record_ids)),
        "distinct_content_hashes": len(set(content_hashes)),
        "duplicate_record_ids": {"groups": dup_map(record_ids)},
        "duplicate_content_hashes": {"groups": dup_map(content_hashes)},
        "duplicate_source_ids": {"groups": dup_map(source_ids)},
        "destructive_deduplication_performed": False,
    }


# ---------------------------------------------------------------------------
# Output helpers (fail-safe, never overwrite)
# ---------------------------------------------------------------------------

def _write_jsonl(path: Path, records: Sequence[Dict[str, Any]]) -> None:
    if path.exists():
        raise FileExistsError(f"refusing to overwrite existing artifact: {path}")
    temp = path.with_name(path.name + ".tmp")
    if temp.exists():
        raise FileExistsError(f"refusing to overwrite existing temporary artifact: {temp}")
    path.parent.mkdir(parents=True, exist_ok=True)
    with temp.open("w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, sort_keys=True, ensure_ascii=False, separators=(",", ":")))
            handle.write("\n")
    os.replace(temp, path)


def _write_json(path: Path, payload: Any) -> None:
    if path.exists():
        raise FileExistsError(f"refusing to overwrite existing artifact: {path}")
    temp = path.with_name(path.name + ".tmp")
    path.parent.mkdir(parents=True, exist_ok=True)
    with temp.open("w", encoding="utf-8") as handle:
        json.dump(payload, handle, indent=2, sort_keys=True, ensure_ascii=False)
        handle.write("\n")
    os.replace(temp, path)


def _git_metadata() -> Dict[str, Any]:
    try:
        commit = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=Path(__file__).resolve().parent.parent.parent,
            capture_output=True, text=True, timeout=10,
        )
        status = subprocess.run(
            ["git", "status", "--porcelain=v1"],
            cwd=Path(__file__).resolve().parent.parent.parent,
            capture_output=True, text=True, timeout=10,
        )
        commit_value = commit.stdout.strip() if commit.returncode == 0 else None
        status_lines = [line for line in status.stdout.splitlines() if line]
        return {
            "git_commit": commit_value,
            "git_working_tree_dirty": bool(status_lines),
            "git_status_porcelain": status_lines[:100],
            "git_status_truncated": len(status_lines) > 100,
        }
    except Exception as exc:
        return {"git_commit": None, "git_working_tree_dirty": None, "git_error": str(exc)}


