def evaluate_code_quality(code: str, docstring: str) -> Dict[str, Any]:
    """Evaluate a function body deterministically without executing it."""
    rejection_reasons: List[str] = []

    if not code or not code.strip():
        return _quality_result(False, "REJECTED", ["empty code"], 0, 0, 0)

    ast_result = _validate_python_quietly(code)
    ast_valid = ast_result.is_valid

    lines = code.split("\n")
    non_blank_lines = [l for l in lines if l.strip()]
    line_count = len(non_blank_lines)
    char_count = len(code)

    # Trivial stub detection: only "pass", "...", or a docstring in the body.
    if _is_trivial_stub(code):
        rejection_reasons.append("trivial_stub")

    # Generated / boilerplate markers.
    lower = code.lower()
    if any(marker in lower for marker in GENERATED_MARKERS):
        rejection_reasons.append("generated_or_boilerplate")

    if not ast_valid:
        rejection_reasons.append(f"ast_invalid:{ast_result.error_type}")

    if not docstring or not docstring.strip():
        rejection_reasons.append("missing_docstring")

    if line_count < 3:
        rejection_reasons.append("too_few_lines")

    status = "ACCEPTED" if not rejection_reasons else "REJECTED"
    return _quality_result(
        ast_valid,
        status,
        rejection_reasons,
        line_count,
        char_count,
        ast_result.comment_ratio,
    )


def _quality_result(
    ast_valid: bool,
    status: str,
    reasons: List[str],
    line_count: int,
    char_count: int,
    comment_ratio: float,
) -> Dict[str, Any]:
    return {
        "ast_valid": ast_valid,
        "quality_status": status,
        "rejection_reasons": reasons,
        "line_count": line_count,
        "char_count": char_count,
        "comment_ratio": round(comment_ratio, 4),
    }


def _validate_python_quietly(code: str) -> Any:
    """Run AST validation, suppressing noisy SyntaxWarnings from corpus code."""
    from scripts.validators.ast_validator import validate_python

    with warnings.catch_warnings():
        warnings.simplefilter("ignore", SyntaxWarning)
        return validate_python(code)


def _is_trivial_stub(code: str) -> bool:
    """Return True if the function body contains only pass/ellipsis/docstring."""
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", SyntaxWarning)
            tree = ast.parse(code)
    except (SyntaxError, IndentationError):
        return False
    funcs = [n for n in ast.walk(tree) if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))]
    if not funcs:
        return False
    for func in funcs:
        body = [s for s in func.body if not (isinstance(s, ast.Expr) and isinstance(getattr(s, "value", None), ast.Constant) and isinstance(getattr(s, "value", None).value, str))]
        if not body:
            return True
        if len(body) == 1 and isinstance(body[0], ast.Pass):
            return True
        if all(isinstance(s, (ast.Pass, ast.Expr)) for s in body):
            return True
    return False


