class _RestrictedUnpickler(pickle.Unpickler):
    """Unpickler that only permits safe, data-only builtin types.

    Loading a pickle is normally code execution; this class restricts the
    resolution of global references so that only immutable/serializable
    container types can be constructed.  Any attempt to load a function,
    class, or other callable raises immediately.
    """

    _SAFE: dict[str, set[str]] = {
        "builtins": {
            "dict", "list", "tuple", "set", "frozenset", "str", "bytes",
            "bytearray", "int", "float", "bool", "complex", "NoneType",
        },
        "collections": {"OrderedDict"},
    }

    def find_class(self, module: str, name: str) -> Any:
        if module in self._SAFE and name in self._SAFE[module]:
            return getattr(__import__(module), name)
        raise pickle.UnpicklingError(f"forbidden global reference: {module}.{name}")


def load_licenses_pkl(path: Path) -> Dict[str, List[Tuple[str, str]]]:
    """Load ``python_licenses.pkl`` with the restricted unpickler.

    Returns a normalized mapping of ``owner/name`` -> list of
    ``(license_file_path, license_text)`` tuples.  Values in the upstream file
    may be a single tuple, a list of tuples, or a list of strings.
    """
    if not path.is_file():
        raise FileNotFoundError(f"licenses pkl not found: {path}")
    with path.open("rb") as handle:
        data = _RestrictedUnpickler(handle).load()

    if not isinstance(data, dict):
        raise ValueError(f"licenses pkl is {type(data).__name__}, expected dict")

    normalized: Dict[str, List[Tuple[str, str]]] = {}
    for nwo, value in data.items():
        if not isinstance(nwo, str):
            continue
        entries = _normalize_license_value(value)
        if entries:
            normalized[nwo] = entries
    return normalized


def _normalize_license_value(value: Any) -> List[Tuple[str, str]]:
    if isinstance(value, tuple) and len(value) == 2 and all(isinstance(x, str) for x in value):
        return [value]
    if isinstance(value, list):
        entries: List[Tuple[str, str]] = []
        for item in value:
            if isinstance(item, tuple) and len(item) == 2 and all(isinstance(x, str) for x in item):
                entries.append(item)
            elif isinstance(item, str):
                entries.append(("", item))
        return entries
    if isinstance(value, str):
        return [("", value)]
    return []


