def acquire(
    raw_dir: Optional[Path] = None,
    filtered_dir: Optional[Path] = None,
    manifest_dir: Optional[Path] = None,
    skip_download: bool = False,
    skip_extract: bool = False,
    max_records: Optional[int] = None,
    only_splits: Optional[Sequence[str]] = None,
    run_id: Optional[str] = None,
) -> Dict[str, Any]:
    """Run the full CodeSearchNet acquisition + processing pipeline."""
    raw_dir = Path(raw_dir) if raw_dir else _default_raw_dir()
    filtered_dir = Path(filtered_dir) if filtered_dir else _default_filtered_dir()
    manifest_dir = Path(manifest_dir) if manifest_dir else _default_manifest_dir()

    archive_path = raw_dir / "python.zip"
    licenses_path = raw_dir / "python_licenses.pkl"
    jsonl_root = raw_dir / "python" / "final" / "jsonl"

    acquisition_date = utc_now_iso()
    effective_run_id = run_id or make_run_id(ZENODO_DOI + EXPECTED_ARCHIVE_MD5)

    # 1. Download + verify archive.
    if not skip_download:
        logger.info("Downloading CodeSearchNet python.zip from Zenodo %s", ZENODO_DOI)
        archive_info = download_archive(
            ZENODO_PYTHON_URL, archive_path, EXPECTED_ARCHIVE_SIZE, EXPECTED_ARCHIVE_MD5
        )
    elif archive_path.exists():
        archive_info = {
            "path": str(archive_path),
            "bytes": archive_path.stat().st_size,
            "md5": _md5_file(archive_path),
            "sha256": sha256_file(archive_path),
            "reused_existing": True,
        }
    else:
        # Archive not required when processing an existing extraction.
        archive_info = {
            "path": None,
            "bytes": None,
            "md5": None,
            "sha256": None,
            "reused_existing": False,
            "skipped": True,
        }

    # 2. Extract (jsonl.gz + licenses pkl; skip the huge dedupe pkl for Category A).
    if not skip_extract:
        logger.info("Extracting archive (jsonl + licenses)")
        jsonl_names = [
            f"python/final/jsonl/train/python_train_{i}.jsonl.gz" for i in range(14)
        ] + [
            "python/final/jsonl/valid/python_valid_0.jsonl.gz",
            "python/final/jsonl/test/python_test_0.jsonl.gz",
            "python_licenses.pkl",
        ]
        extracted = extract_archive(archive_path, raw_dir, include_names=jsonl_names)
    else:
        extracted = []

    # 3. Load license evidence.
    if not licenses_path.exists():
        raise FileNotFoundError(f"licenses pkl not extracted: {licenses_path}")
    logger.info("Loading per-repository license evidence (restricted unpickler)")
    license_map = load_licenses_pkl(licenses_path)

    # 4. Process jsonl.gz files (streamed; no full-record in-memory accumulation).
    jsonl_files = sorted(jsonl_root.glob("*/python_*.jsonl.gz"))
    if not jsonl_files:
        raise FileNotFoundError(f"no jsonl.gz files found under {jsonl_root}")

    run_dir = filtered_dir / f"codesearchnet_{effective_run_id}"
    run_dir.mkdir(parents=True, exist_ok=True)
    accepted_path = run_dir / "codesearchnet_canonical_accepted.jsonl"
    rejected_path = run_dir / "codesearchnet_rejected.jsonl"
    checkpoint_path = run_dir / "checkpoint.json"

    checkpoint = _load_checkpoint(checkpoint_path)
    completed_files: set = set(checkpoint.get("completed_files", []))
    processed = checkpoint.get("records_processed", 0)
    accepted_count = checkpoint.get("records_accepted", 0)
    rejected_count = checkpoint.get("records_rejected", 0)

    if not completed_files and (accepted_path.exists() or rejected_path.exists()):
        raise FileExistsError("output files already exist; use a new run_id")

    if completed_files:
        # Repair a mid-file crash: drop uncheckpointed trailing records so the
        # interrupted source file is reprocessed without duplication.
        _repair_output_tail(accepted_path, accepted_count)
        _repair_output_tail(rejected_path, rejected_count)

    open_mode = "a" if completed_files else "w"

    record_id_counter: Counter = Counter()
    content_hash_counter: Counter = Counter()
    source_id_counter: Counter = Counter()
    license_status_counts: Counter = Counter()
    split_counts: Counter = Counter()
    repo_counts: Counter = Counter()
    license_cache: Dict[str, Dict[str, Any]] = {}

    output_paths: Dict[str, str] = {
        "accepted": str(accepted_path),
        "rejected": str(rejected_path),
    }

    with accepted_path.open(open_mode, encoding="utf-8") as af, rejected_path.open(open_mode, encoding="utf-8") as rf:
        for jsonl_file in jsonl_files:
            file_partition = _partition_from_path(jsonl_file)
            if only_splits and file_partition not in only_splits:
                continue
            if jsonl_file.name in completed_files:
                continue
            logger.info("Processing %s (partition=%s)", jsonl_file.name, file_partition)
            records, info = read_jsonl_gz(jsonl_file)
            for line_number, source_record in records:
                if max_records is not None and processed >= max_records:
                    break

                errors = validate_source_record(source_record, line_number)
                if errors:
                    reject_entry = {
                        "record_id": None,
                        "source_file": jsonl_file.name,
                        "source_line": line_number,
                        "rejection_reasons": errors,
                    }
                    rf.write(_jsonl_line(reject_entry))
                    rejected_count += 1
                    processed += 1
                    continue

                repo = source_record.get("repo", "")
                language = source_record.get("language", "")
                if language != EXPECTED_LANGUAGE:
                    reject_entry = {
                        "record_id": None,
                        "source_file": jsonl_file.name,
                        "source_line": line_number,
                        "rejection_reasons": [f"language {language!r} != python"],
                    }
                    rf.write(_jsonl_line(reject_entry))
                    rejected_count += 1
                    processed += 1
                    continue

                license_info = license_cache.get(repo)
                if license_info is None:
                    license_info = classify_license(repo, license_map.get(repo, []))
                    license_cache[repo] = license_info
                quality = evaluate_code_quality(source_record.get("code", ""), source_record.get("docstring", ""))
                record = build_canonical_record(
                    source_record,
                    license_info,
                    quality,
                    source_file=jsonl_file.name,
                    line_number=line_number,
                    run_id=effective_run_id,
                    acquisition_date=acquisition_date,
                )
                record["dedup_status"] = "audited"

                record_id_counter[record["record_id"]] += 1
                content_hash_counter[record["content_hash"]] += 1
                source_id_counter[record["original_record_id"]] += 1
                license_status_counts[record["license_status"]] += 1
                split_counts[record["split"]] += 1
                repo_counts[repo] += 1

                if quality["quality_status"] == "ACCEPTED" and license_info["license_status"] == LICENSE_APPROVED:
                    af.write(_jsonl_line(record))
                    accepted_count += 1
                else:
                    reject_entry = {
                        "record_id": record["record_id"],
                        "content_hash": record["content_hash"],
                        "source_file": jsonl_file.name,
                        "source_line": line_number,
                        "repository_name": repo,
                        "license_status": record["license_status"],
                        "quality_status": record["quality_status"],
                        "rejection_reasons": record["rejection_reasons"],
                    }
                    rf.write(_jsonl_line(reject_entry))
                    rejected_count += 1
                processed += 1

            if max_records is not None and processed >= max_records:
                break
            completed_files.add(jsonl_file.name)
            _write_checkpoint(
                checkpoint_path,
                completed_files=sorted(completed_files),
                records_processed=processed,
                records_accepted=accepted_count,
                records_rejected=rejected_count,
            )

    dedup = _dedup_report(record_id_counter, content_hash_counter, source_id_counter, processed)

    license_report = {
        "license_status_counts": dict(license_status_counts),
        "unique_repositories": len(repo_counts),
        "repository_count": len(repo_counts),
        "license_approved_count": license_status_counts.get(LICENSE_APPROVED, 0),
        "license_review_required_count": license_status_counts.get(LICENSE_REVIEW_REQUIRED, 0),
        "license_ineligible_count": license_status_counts.get(LICENSE_INELIGIBLE, 0),
        "provenance_insufficient_count": license_status_counts.get(PROVENANCE_INSUFFICIENT, 0),
    }

    manifest_dir.mkdir(parents=True, exist_ok=True)
    manifest = {
        "run_id": effective_run_id,
        "generated_at": utc_now_iso(),
        "source": SOURCE,
        "source_dataset": SOURCE_DATASET,
        "source_version": ZENODO_DOI,
        "zenodo_record_id": ZENODO_RECORD_ID,
        "archive": archive_info,
        "schema_version": SCHEMA_VERSION,
        "processor_version": PROCESSOR_VERSION,
        "transformation_version": TRANSFORMATION_VERSION,
        "counts": {
            "records_processed": processed,
            "records_accepted": accepted_count,
            "records_rejected": rejected_count,
            "all_records_audited": processed,
        },
        "split_counts": dict(split_counts),
        "license": license_report,
        "deduplication": dedup,
        "outputs": output_paths,
        "git": _git_metadata(),
        "python_version": sys.version,
        "platform": platform.platform(),
        "python_language_filter": EXPECTED_LANGUAGE,
        "max_records": max_records,
        "only_splits": list(only_splits) if only_splits else None,
    }
    manifest_path = manifest_dir / f"codesearchnet_acquisition_{effective_run_id}.json"
    _write_json(manifest_path, manifest)
    output_paths["manifest"] = str(manifest_path)

    return manifest


def _jsonl_line(record: Dict[str, Any]) -> str:
    return json.dumps(record, sort_keys=True, ensure_ascii=False, separators=(",", ":")) + "\n"


def _load_checkpoint(path: Path) -> Dict[str, Any]:
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return {}


def _write_checkpoint(
    path: Path,
    completed_files: List[str],
    records_processed: int,
    records_accepted: int,
    records_rejected: int,
) -> None:
    payload = {
        "completed_files": completed_files,
        "records_processed": records_processed,
        "records_accepted": records_accepted,
        "records_rejected": records_rejected,
        "updated_at": utc_now_iso(),
    }
    temp = path.with_name(path.name + ".tmp")
    last_exc: Optional[BaseException] = None
    for attempt in range(6):
        try:
            with temp.open("w", encoding="utf-8") as handle:
                json.dump(payload, handle, indent=2, sort_keys=True)
                handle.write("\n")
            os.replace(temp, path)
            return
        except OSError as exc:
            last_exc = exc
            logger.warning(
                "Checkpoint write attempt %d failed (%s); retrying", attempt + 1, exc
            )
            try:
                if temp.exists():
                    temp.unlink()
            except OSError:
                pass
            time.sleep(min(2**attempt, 30))
    raise last_exc  # type: ignore[misc]


def _repair_output_tail(path: Path, expected_lines: int) -> int:
    """Truncate an output file back to the checkpointed line count.

    A crash between writing a source file's records and persisting the
    checkpoint leaves uncheckpointed trailing lines.  Removing them before
    resuming keeps the accepted/rejected files exact and avoids duplicates
    when the interrupted source file is reprocessed.
    """
    if not path.exists():
        if expected_lines:
            raise RuntimeError(
                f"{path} missing but checkpoint expects {expected_lines} records"
            )
        return 0
    with path.open("rb+") as handle:
        offset = 0
        for _ in range(expected_lines):
            line = handle.readline()
            if not line:
                raise RuntimeError(
                    f"{path} has fewer than checkpoint's {expected_lines} records; refusing to resume"
                )
            offset = handle.tell()
        leftover = handle.readline()
        if leftover:
            extra = 1 + sum(1 for _ in handle)
            handle.truncate(offset)
            logger.warning(
                "Repaired %s: truncated %d uncheckpointed trailing records", path, extra
            )
    return expected_lines


def _dedup_report(
    record_id_counter: Counter,
    content_hash_counter: Counter,
    source_id_counter: Counter,
    total: int,
) -> Dict[str, Any]:
    def groups(counter: Counter) -> Dict[str, int]:
        return {str(k): c for k, c in sorted(counter.items()) if c > 1}

    return {
        "records_audited": total,
        "distinct_record_ids": len(record_id_counter),
        "distinct_content_hashes": len(content_hash_counter),
        "duplicate_record_ids": {"groups": groups(record_id_counter)},
        "duplicate_content_hashes": {"groups": groups(content_hash_counter)},
        "duplicate_source_ids": {"groups": groups(source_id_counter)},
        "destructive_deduplication_performed": False,
    }


def _partition_from_path(path: Path) -> str:
    name = path.name
    if "train" in name:
        return "train"
    if "valid" in name:
        return "valid"
    if "test" in name:
        return "test"
    return "unknown"


def _build_cli() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Acquire and process CodeSearchNet Python subset.")
    parser.add_argument("--raw-dir", type=Path, default=None, help="raw data root (defaults to config CODESEARCHNET_DIR)")
    parser.add_argument("--filtered-dir", type=Path, default=None, help="filtered output root (defaults to config STAGE2_DIR)")
    parser.add_argument("--manifest-dir", type=Path, default=None, help="manifest output root")
    parser.add_argument("--skip-download", action="store_true", help="reuse an existing archive")
    parser.add_argument("--skip-extract", action="store_true", help="reuse an existing extraction")
    parser.add_argument("--max-records", type=int, default=None, help="limit records processed (pilot)")
    parser.add_argument("--only-split", action="append", default=None, choices=["train", "valid", "test"], help="restrict to split (repeatable)")
    parser.add_argument("--run-id", default=None, help="explicit run id")
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = _build_cli().parse_args(argv)
    try:
        manifest = acquire(
            raw_dir=args.raw_dir,
            filtered_dir=args.filtered_dir,
            manifest_dir=args.manifest_dir,
            skip_download=args.skip_download,
            skip_extract=args.skip_extract,
            max_records=args.max_records,
            only_splits=args.only_split,
            run_id=args.run_id,
        )
    except Exception as exc:
        logger.exception("CodeSearchNet acquisition failed")
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    print(json.dumps(manifest["counts"], indent=2, sort_keys=True))
    print(f"Manifest written to: {manifest['outputs']['manifest']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
