def validate_source_record(record: Any, line_number: int) -> List[str]:
    errors: List[str] = []
    if not isinstance(record, dict):
        return [f"line {line_number}: parsed value is {type(record).__name__}, expected object"]
    for field in CSN_REQUIRED_FIELDS:
        if field not in record:
            errors.append(f"line {line_number}: missing required field {field!r}")
    for field in ("repo", "path", "func_name", "original_string", "language", "code", "docstring", "sha", "partition", "url"):
        if field in record and not isinstance(record[field], str):
            errors.append(f"line {line_number}: field {field!r} is {type(record[field]).__name__}, expected str")
    return errors


def read_jsonl_gz(path: Path) -> Tuple[List[Tuple[int, Dict[str, Any]]], Dict[str, Any]]:
    if not path.is_file():
        raise FileNotFoundError(f"input file does not exist: {path}")
    records: List[Tuple[int, Dict[str, Any]]] = []
    parse_errors: List[str] = []
    with gzip.open(path, "rt", encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            if not line.strip():
                continue
            try:
                parsed = json.loads(line)
            except json.JSONDecodeError as exc:
                parse_errors.append(f"line {line_number}: invalid JSON: {exc.msg}")
                continue
            if not isinstance(parsed, dict):
                parse_errors.append(f"line {line_number}: parsed value is {type(parsed).__name__}, expected object")
                continue
            records.append((line_number, parsed))

    info = {
        "path": str(path),
        "filename": path.name,
        "bytes": path.stat().st_size,
        "sha256": sha256_file(path),
        "records": len(records),
        "parse_errors": len(parse_errors),
    }
    return records, info


