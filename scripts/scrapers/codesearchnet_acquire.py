def download_archive(
    url: str,
    dest: Path,
    expected_size: int,
    expected_md5: Optional[str] = None,
    resume: bool = True,
) -> Dict[str, Any]:
    """Download the archive with resumable support and verify integrity.

    Uses ``curl`` when available (resume, retry); falls back to a streaming
    ``urllib`` download.  Never overwrites an existing verified archive.
    """
    import urllib.request

    dest.parent.mkdir(parents=True, exist_ok=True)

    if dest.exists() and dest.stat().st_size == expected_size:
        md5_ok = True
        if expected_md5:
            md5_ok = _md5_file(dest) == expected_md5
        if md5_ok:
            return {
                "path": str(dest),
                "bytes": dest.stat().st_size,
                "md5": _md5_file(dest),
                "sha256": sha256_file(dest),
                "reused_existing": True,
            }

    curl = _which("curl")
    if curl:
        cmd = [curl, "-sSL"]
        if resume:
            cmd += ["-C", "-"]
        cmd += ["--retry", "5", "--retry-delay", "3", "--retry-all-errors", "-o", str(dest), url]
        result = subprocess.run(cmd, capture_output=True, text=True, timeout=3600 * 6)
        if result.returncode != 0:
            raise RuntimeError(f"curl download failed: {result.stderr[:500]}")

    if not dest.exists():
        req = urllib.request.Request(url)
        if resume and dest.exists():
            req.add_header("Range", f"bytes={dest.stat().st_size}-")
        with urllib.request.urlopen(req, timeout=120) as resp, dest.open("ab" if resume else "wb") as out:
            for chunk in iter(lambda: resp.read(1024 * 1024), b""):
                out.write(chunk)

    size = dest.stat().st_size
    if size != expected_size:
        raise RuntimeError(f"archive size mismatch: {size} != expected {expected_size}")

    md5 = _md5_file(dest)
    if expected_md5 and md5 != expected_md5:
        raise RuntimeError(f"archive md5 mismatch: {md5} != expected {expected_md5}")

    return {
        "path": str(dest),
        "bytes": size,
        "md5": md5,
        "sha256": sha256_file(dest),
        "reused_existing": False,
    }


def _which(name: str) -> Optional[str]:
    from shutil import which

    return which(name)


def _md5_file(path: Path) -> str:
    digest = hashlib.md5()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def extract_archive(
    zip_path: Path,
    dest_dir: Path,
    include_names: Optional[Sequence[str]] = None,
) -> List[Dict[str, Any]]:
    """Safely extract members of a zip archive (zip-slip protected)."""
    dest_dir.mkdir(parents=True, exist_ok=True)
    extracted: List[Dict[str, Any]] = []

    with zipfile.ZipFile(zip_path) as zf:
        for info in zf.infolist():
            name = info.filename
            if include_names and not any(name.endswith(n) or name == n for n in include_names):
                continue
            target = _safe_join(dest_dir, name)
            if target is None:
                raise RuntimeError(f"unsafe zip member path: {name}")
            if info.is_dir():
                target.mkdir(parents=True, exist_ok=True)
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            with zf.open(info) as src, target.open("wb") as out:
                for chunk in iter(lambda: src.read(1024 * 1024), b""):
                    out.write(chunk)
            extracted.append(
                {
                    "name": name,
                    "path": str(target),
                    "bytes": info.file_size,
                }
            )
    return extracted


def _safe_join(base: Path, member: str) -> Optional[Path]:
    base = base.resolve()
    candidate = (base / member).resolve()
    if candidate == base or base in candidate.parents:
        return candidate
    return None


