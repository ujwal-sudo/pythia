"""Content-quality rules for code records, applied once as data arrives.

One function, used in two places so every token sees the same rules:
  * `CurationRun` (new batches: clean-on-download)
  * `tokenize_corpus` (batches 001-006, which were cleaned before these rules)

Only the "code" family is filtered; prose/docs/notebook records are passed
through because "doesn't parse as Python" is the normal case for them.
Bump QUALITY_VERSION whenever a rule changes: tokenized shards record it and
`finalize` refuses to mix versions.
"""

from __future__ import annotations

import ast
import re
import warnings

QUALITY_VERSION = "q1"

MIN_CHARS = 100
MAX_CHARS = 100_000
MAX_LINE = 1000
MAX_MEAN_LINE = 100
MIN_ALPHA = 0.25

_AUTOGEN = re.compile(
    r"auto-?generated|generated by (?!the\b)|do not (edit|modify)|"
    r"code generated|this file was generated",
    re.IGNORECASE,
)
_SECRET = re.compile(
    r"AKIA[0-9A-Z]{16}|-----BEGIN [A-Z ]*PRIVATE KEY-----|gh[pousr]_[A-Za-z0-9]{36}|"
    r"xox[abposr]-[A-Za-z0-9-]{10,}|sk-[A-Za-z0-9]{32,}|AIza[0-9A-Za-z_-]{35}"
)


def reject_reason(text: str, family: str, repo_path: str = "") -> str | None:
    """Return why a record should be dropped, or None to keep it."""
    if _SECRET.search(text):  # every family: never train on credentials
        return "secret"
    if family != "code":
        return None
    path = repo_path.replace("\\", "/").lower()
    if "/migrations/" in f"/{path}":
        return "migration"
    if len(text) < MIN_CHARS:
        return "too_short"
    if len(text) > MAX_CHARS:
        return "too_long"
    lines = text.split("\n")
    if max(map(len, lines)) > MAX_LINE or len(text) / len(lines) > MAX_MEAN_LINE:
        return "long_lines"
    if sum(ch.isalpha() for ch in text) / len(text) < MIN_ALPHA:
        return "low_alpha"
    if _AUTOGEN.search(text[:1000]):
        return "autogenerated"
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")  # invalid-escape warnings are noise here
            ast.parse(text)
    except (SyntaxError, ValueError, RecursionError, MemoryError):
        return "syntax"  # mostly Python 2
    return None
