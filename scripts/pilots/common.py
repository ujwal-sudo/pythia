def utc_now_iso() -> str:
    return datetime.now(UTC).replace(microsecond=0).isoformat()


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_text(text: str) -> str:
    return sha256_bytes(text.encode("utf-8"))


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def normalize_newlines(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n")


def normalize_for_hash(code: str) -> str:
    return "\n".join(line.rstrip() for line in normalize_newlines(code).split("\n"))


def dedup_hash(code: str) -> str:
    return sha256_text(normalize_for_hash(code))


def clean_code(code: str) -> str:
    return normalize_newlines(code).strip()


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    temporary.replace(path)


def write_jsonl(path: Path, records: Iterable[dict[str, Any]]) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    count = 0
    temporary = path.with_suffix(path.suffix + ".tmp")
    with temporary.open("w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, sort_keys=True) + "\n")
            count += 1
    temporary.replace(path)
    return count


def download(url: str, destination: Path, expected_sha256: str | None = None, max_bytes: int | None = None) -> dict[str, Any]:
    destination.parent.mkdir(parents=True, exist_ok=True)
    last_error: Exception | None = None
    for attempt in range(1, 4):
        try:
            with requests.get(url, stream=True, timeout=180, headers={"User-Agent": "pythia-bounded-pilot/1"}) as response:
                response.raise_for_status()
                declared = response.headers.get("Content-Length")
                if max_bytes is not None and declared is not None and int(declared) > max_bytes:
                    raise RuntimeError(f"declared size {declared} exceeds cap {max_bytes}")
                with destination.open("wb") as handle:
                    for chunk in response.iter_content(chunk_size=1024 * 1024):
                        if chunk:
                            handle.write(chunk)
            size = destination.stat().st_size
            if max_bytes is not None and size > max_bytes:
                destination.unlink(missing_ok=True)
                raise RuntimeError(f"downloaded size {size} exceeds cap {max_bytes}")
            digest = sha256_file(destination)
            if expected_sha256 is not None and digest != expected_sha256:
                raise RuntimeError(f"sha256 mismatch for {url}: {digest} != {expected_sha256}")
            return {"url": url, "path": str(destination), "size": size, "sha256": digest, "attempts": attempt, "acquired_at": utc_now_iso()}
        except Exception as error:
            last_error = error
            if destination.exists():
                destination.unlink()
            if attempt < 3:
                time.sleep(2 * attempt)
    raise RuntimeError(f"download failed after retries: {url}: {last_error}")


def safe_extract(archive_path: Path, destination: Path) -> None:
    destination.mkdir(parents=True, exist_ok=True)
    with tarfile.open(archive_path, "r:*") as archive:
        try:
            archive.extractall(destination, filter="data")
        except TypeError:
            archive.extractall(destination)


def archive_root(destination: Path) -> Path:
    children = [path for path in destination.iterdir() if path.is_dir()]
    if len(children) != 1:
        raise RuntimeError(f"expected one extracted root in {destination}, found {len(children)}")
    return children[0]


def copy_verified(source: Path, destination: Path, expected_sha256: str | None = None) -> dict[str, Any]:
    destination.parent.mkdir(parents=True, exist_ok=True)
    digest = sha256_file(source)
    if expected_sha256 is not None and digest != expected_sha256:
        raise RuntimeError(f"sha256 mismatch for {source}: {digest} != {expected_sha256}")
    if destination.exists():
        if sha256_file(destination) != digest:
            raise RuntimeError(f"refusing to replace different file: {destination}")
    else:
        shutil.copyfile(source, destination)
    return {"source": str(source), "path": str(destination), "sha256": digest, "size": destination.stat().st_size}


def load_csn_hashes(path: Path) -> set[str]:
    hashes: set[str] = set()
    with path.open("r", encoding="utf-8") as handle:
        for line in handle:
            if not line.strip():
                continue
            record = json.loads(line)
            for key in ("normalized_hash", "content_hash"):
                value = record.get(key)
                if isinstance(value, str) and value:
                    hashes.add(value)
    return hashes


def path_parts(relative_path: Path) -> set[str]:
    return {part.lower() for part in relative_path.parts}


def is_test_path(relative_path: Path) -> bool:
    parts = path_parts(relative_path)
    name = relative_path.name.lower()
    return bool(parts & TEST_PARTS) or name.startswith("test_") or name.endswith("_test.py")


def is_vendor_path(relative_path: Path) -> bool:
    return bool(path_parts(relative_path) & VENDOR_PARTS) or "site-packages" in path_parts(relative_path)


def is_noncode_path(relative_path: Path) -> bool:
    return bool(path_parts(relative_path) & NONCODE_PARTS)


def qualified_name(node: ast.AST, parents: dict[ast.AST, ast.AST]) -> str:
    names: list[str] = []
    current: ast.AST | None = node
    while current is not None:
        name = getattr(current, "name", None)
        if isinstance(name, str):
            names.append(name)
        current = parents.get(current)
    return ".".join(reversed(names))


def source_start(node: ast.AST) -> int:
    decorators = getattr(node, "decorator_list", [])
    lines = [getattr(node, "lineno", 1), *(getattr(item, "lineno", 1) for item in decorators)]
    return min(lines)


def extract_units(source: str, relative_path: Path) -> tuple[list[dict[str, Any]], str | None]:
    try:
        tree = ast.parse(source)
    except (IndentationError, SyntaxError) as error:
        return [], f"{type(error).__name__}: {error.msg}"
    except (MemoryError, RecursionError):
        raise
    except Exception as error:
        return [], f"{type(error).__name__}: {error}"

    parents: dict[ast.AST, ast.AST] = {}
    for parent in ast.walk(tree):
        for child in ast.iter_child_nodes(parent):
            parents[child] = parent

    units: list[dict[str, Any]] = []
    seen_ranges: set[tuple[int, int]] = set()
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        parent = parents.get(node)
        if isinstance(parent, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        segment = ast.get_source_segment(source, node)
        if not segment:
            continue
        start = source_start(node)
        end = getattr(node, "end_lineno", None) or start
        seen_ranges.add((start, end))
        units.append(
            {
                "code": segment,
                "kind": "method" if isinstance(parent, ast.ClassDef) else "function",
                "qualified_name": qualified_name(node, parents),
                "line_start": start,
                "line_end": end,
            }
        )

    covered: set[int] = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            start = source_start(node)
            end = getattr(node, "end_lineno", None) or start
            covered.update(range(start, end + 1))

    lines = source.splitlines()
    block_start: int | None = None
    block_lines: list[str] = []
    for line_number, line in enumerate(lines, start=1):
        if line_number in covered:
            if block_start is not None:
                block = "\n".join(block_lines).strip()
                if block:
                    units.append(
                        {
                            "code": block,
                            "kind": "module",
                            "qualified_name": "module",
                            "line_start": block_start,
                            "line_end": line_number - 1,
                        }
                    )
                block_start = None
                block_lines = []
            continue
        if block_start is None and line.strip():
            block_start = line_number
        if block_start is not None:
            block_lines.append(line)
    if block_start is not None:
        block = "\n".join(block_lines).strip()
        if block:
            units.append(
                {
                    "code": block,
                    "kind": "module",
                    "qualified_name": "module",
                    "line_start": block_start,
                    "line_end": len(lines),
                }
            )

    unique: list[dict[str, Any]] = []
    seen_hashes: set[str] = set()
    for unit in units:
        code = clean_code(unit["code"])
        digest = dedup_hash(code)
        if digest in seen_hashes:
            continue
        seen_hashes.add(digest)
        unit["code"] = code
        unit["content_hash"] = digest
        unique.append(unit)
    return unique, None


def evaluate_code(code: str, include_pep8: bool = True) -> dict[str, Any]:
    cleaned = clean_code(code)
    if not cleaned:
        return {"accepted": False, "reason": "empty"}
    lowered = cleaned.lower()
    if any(marker in lowered for marker in GENERATED_MARKERS):
        return {"accepted": False, "reason": "generated_or_vendor_marker"}
    validation = validate_python(cleaned)
    if not validation.is_valid:
        return {"accepted": False, "reason": "ast_invalid"}
    tokens = provisional_token_count(cleaned)
    if tokens < MIN_TOKEN_LENGTH:
        return {"accepted": False, "reason": "too_short", "tokens": tokens}
    if tokens > MAX_TOKEN_LENGTH:
        return {"accepted": False, "reason": "too_long", "tokens": tokens}
    if validation.comment_ratio < MIN_COMMENT_RATIO:
        return {"accepted": False, "reason": "low_documentation", "tokens": tokens}
    pep8_violations = measure_pep8_violations(cleaned) if include_pep8 else 0
    if pep8_violations > PEP8_MAX_VIOLATIONS:
        return {"accepted": False, "reason": "pep8", "tokens": tokens}
    return {
        "accepted": True,
        "reason": "accepted",
        "tokens": tokens,
        "chars": len(cleaned),
        "comment_ratio": validation.comment_ratio,
        "pep8_violations": pep8_violations,
        "function_count": validation.function_count,
        "class_count": validation.class_count,
        "node_count": validation.node_count,
    }


def make_record(
    *,
    source: str,
    source_dataset: str,
    source_family: str,
    source_url: str,
    repository: str,
    revision: str,
    file_path: str,
    unit: dict[str, Any],
    quality: dict[str, Any],
    license_spdx: str,
    license_path: str,
    acquired_at: str,
    extra: dict[str, Any] | None = None,
) -> dict[str, Any]:
    digest = unit["content_hash"]
    identity = f"{source}|{repository}|{revision}|{file_path}|{unit['qualified_name']}|{unit['line_start']}|{digest}"
    record: dict[str, Any] = {
        "record_id": sha256_text(identity)[:24],
        "source": source,
        "source_dataset": source_dataset,
        "source_type": "filtered",
        "source_family": source_family,
        "source_url": source_url,
        "repository_name": repository,
        "commit_sha": revision,
        "file_path": file_path,
        "qualified_name": unit["qualified_name"],
        "unit_kind": unit["kind"],
        "line_start": unit["line_start"],
        "line_end": unit["line_end"],
        "code": unit["code"],
        "char_count": quality["chars"],
        "provisional_token_count": quality["tokens"],
        "token_count_status": "PROVISIONAL",
        "content_hash": digest,
        "normalized_hash": digest,
        "license": license_spdx,
        "license_spdx": license_spdx,
        "license_status": "LICENSE_APPROVED_FOR_INTENDED_USE",
        "license_evidence_paths": [license_path],
        "acquisition_date": acquired_at,
        "pipeline_version": PIPELINE_VERSION,
        "ast_parse_status": "VALID",
        "comment_ratio": round(float(quality["comment_ratio"]), 6),
        "pep8_violations": quality["pep8_violations"],
        "function_count": quality["function_count"],
        "class_count": quality["class_count"],
        "node_count": quality["node_count"],
        "quality_status": "ACCEPTED",
        "dedup_status": "UNIQUE",
        "partition": "code",
    }
    if extra:
        record.update(extra)
    return record


class PilotStats:
    def __init__(self) -> None:
        self.values: Counter[str] = Counter()
        self.reasons: Counter[str] = Counter()

    def increment(self, key: str, amount: int = 1) -> None:
        self.values[key] += amount

    def reject(self, reason: str) -> None:
        self.reasons[reason] += 1

    def as_dict(self) -> dict[str, Any]:
        return {"counts": dict(sorted(self.values.items())), "rejection_reasons": dict(sorted(self.reasons.items()))}


def process_code_file(
    *,
    source_path: Path,
    relative_path: Path,
    source: str,
    source_dataset: str,
    repository: str,
    revision: str,
    source_url: str,
    license_spdx: str,
    license_path: str,
    acquired_at: str,
    csn_hashes: set[str],
    seen_hashes: set[str],
    stats: PilotStats,
    records: list[dict[str, Any]],
    partition: str,
    max_records: int | None = None,
) -> None:
    stats.increment("files_seen")
    try:
        source = source_path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        stats.increment("files_encoding_invalid")
        return
    except OSError:
        stats.increment("files_io_error")
        return
    stats.increment("file_bytes", len(source.encode("utf-8")))
    units, error = extract_units(source, relative_path)
    if error is not None:
        stats.increment("files_ast_invalid")
        stats.reject("file_ast_invalid")
        return
    stats.increment("files_ast_valid")
    for unit in units:
        if max_records is not None and len(records) >= max_records:
            stats.increment("record_cap_reached")
            return
        stats.increment("units_seen")
        quality = evaluate_code(unit["code"])
        if not quality["accepted"]:
            stats.reject(str(quality["reason"]))
            continue
        digest = unit["content_hash"]
        if digest in csn_hashes:
            stats.reject("duplicate_csn")
            continue
        if digest in seen_hashes:
            stats.reject("duplicate_pilot")
            continue
        seen_hashes.add(digest)
        stats.increment("units_accepted")
        stats.increment("accepted_chars", quality["chars"])
        stats.increment("accepted_tokens", quality["tokens"])
        stats.increment(f"accepted_{partition}")
        record = make_record(
            source="cpython" if source_dataset == "cpython_lib" else "github",
            source_dataset=source_dataset,
            source_family="code",
            source_url=source_url,
            repository=repository,
            revision=revision,
            file_path=relative_path.as_posix(),
            unit=unit,
            quality=quality,
            license_spdx=license_spdx,
            license_path=license_path,
            acquired_at=acquired_at,
            extra={"partition": partition},
        )
        records.append(record)


def iter_archive_python(archive_path: Path) -> Iterator[tuple[str, bytes]]:
    if zipfile.is_zipfile(archive_path):
        with zipfile.ZipFile(archive_path) as archive:
            for name in sorted(archive.namelist()):
                if name.endswith(".py"):
                    yield name, archive.read(name)
        return
    with tarfile.open(archive_path, "r:*") as archive:
        for member in archive.getmembers():
            if member.isfile() and member.name.endswith(".py"):
                handle = archive.extractfile(member)
                if handle is not None:
                    yield member.name, handle.read()


def find_license(root: Path, filename: str) -> Path:
    direct = root / filename
    if direct.is_file():
        return direct
    for candidate in sorted(root.iterdir()):
        if candidate.is_file() and candidate.name.lower() == filename.lower():
            return candidate
    raise FileNotFoundError(f"license file {filename} not found under {root}")
